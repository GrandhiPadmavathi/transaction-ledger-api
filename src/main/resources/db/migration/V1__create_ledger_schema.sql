CREATE TABLE accounts (
    id          VARCHAR(36)    NOT NULL,
    name        VARCHAR(255)   NOT NULL,
    balance     DECIMAL(19, 2) DEFAULT 0 NOT NULL,
    created_at  TIMESTAMP(6)   NOT NULL,
    CONSTRAINT pk_accounts PRIMARY KEY (id),
    CONSTRAINT chk_accounts_name_not_blank CHECK (LENGTH(TRIM(name)) > 0),
    CONSTRAINT chk_accounts_balance_non_negative CHECK (balance >= 0)
);

CREATE TABLE transactions (
    id            VARCHAR(36)    NOT NULL,
    entry_no      BIGINT         GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    account_id    VARCHAR(36)    NOT NULL,
    type          VARCHAR(6)     NOT NULL,
    amount        DECIMAL(19, 2) NOT NULL,
    description   VARCHAR(255),
    reference_id  VARCHAR(100)   NOT NULL,
    transfer_id   VARCHAR(36),
    created_at    TIMESTAMP(6)   NOT NULL,
    CONSTRAINT pk_transactions PRIMARY KEY (id),
    CONSTRAINT uq_transactions_entry_no UNIQUE (entry_no),
    CONSTRAINT fk_transactions_account FOREIGN KEY (account_id) REFERENCES accounts (id),
    CONSTRAINT uq_transactions_account_reference UNIQUE (account_id, reference_id),
    CONSTRAINT chk_transactions_type CHECK (type IN ('CREDIT', 'DEBIT')),
    CONSTRAINT chk_transactions_amount_positive CHECK (amount > 0),
    CONSTRAINT chk_transactions_reference_not_blank CHECK (LENGTH(TRIM(reference_id)) > 0)
);

CREATE INDEX idx_transactions_account_created ON transactions (account_id, created_at DESC, entry_no DESC);
CREATE INDEX idx_transactions_account_type_created ON transactions (account_id, type, created_at DESC, entry_no DESC);
CREATE INDEX idx_transactions_transfer ON transactions (transfer_id);
